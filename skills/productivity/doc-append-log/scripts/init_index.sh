#!/bin/sh
# 初始化文档索引 INDEX.md（目录无关：先定位，再建）。
# 已存在则跳过，绝不覆盖已有内容（遵循"只追加、不改写"）。
# 用法：init_index.sh [文档目录]
set -eu

SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
DIR=$(sh "$SCRIPT_DIR/locate_docs.sh" "${1:-}")
INDEX="$DIR/INDEX.md"

if [ -f "$INDEX" ]; then
  echo "INDEX.md 已存在，跳过（不改写）: $INDEX" >&2
  exit 0
fi

mkdir -p "$DIR"

cat > "$INDEX" <<'EOF'
# 文档/日志索引（时间线与阅读入口）

> 本文件是文档目录的唯一索引，供 CodeBuddy / Claude Code / Codex 等智能体快速掌握项目历史。
> **约定（只追加，不改写）：
> 1. 每篇历史/结论文档创建后不再修改其内容（保留原貌，作为历史）。
> 2. 新增内容时新建一个 `YYYY-MM-DD_主题.md` 文件，并**在本文末尾追加一行**索引项；不回改旧文档。
> 3. 智能体阅读顺序：先读本 `INDEX.md` → 按"状态"定位需关注的文档 → 按需精读对应 md。
> 4. 状态含义：`当前事实`=最新且生效；`当前参考`=仍有效但属某专题沉淀；`历史背景`=已被取代，仅作溯源。

---

## 时间线 / 索引

| 日期 | 文件 | 状态 | 一句话摘要 |
| --- | --- | --- | --- |
| 示例 | [示例.md](示例.md) | 当前事实 | 一句话摘要（创建后请删除此示例行） |

<!-- APPEND_NEW_DOC_HERE -->

---

## 当前事实入口

- 按上表"状态"定位需关注的文档；`当前事实` 为最新且生效。

---

<!-- 追加格式（在 APPEND_NEW_DOC_HERE 上方插入一行）：
| 2026-08-15 | 2026-08-15_某主题.md | 当前事实 | 一句话摘要 |
-->
EOF

echo "已创建 INDEX.md: $INDEX"
